#!/usr/bin/env python3
"""Safely add the browser-patch include to a standard Nginx virtual host."""
import argparse
import re
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--root", required=True, help="teslamate-cn-patches checkout")
parser.add_argument("--config", help="explicit Nginx vhost file")
args = parser.parse_args()

def candidates():
    patterns = ("/etc/nginx/sites-enabled/*", "/etc/nginx/conf.d/*", "/etc/nginx/sites-available/*")
    out = []
    for pattern in patterns:
        for path in Path("/").glob(pattern.lstrip("/")):
            if path.is_file() and "server" in path.read_text(errors="ignore") and "proxy_pass" in path.read_text(errors="ignore"):
                out.append(path)
    return list(dict.fromkeys(out))

target = Path(args.config) if args.config else None
if target is None:
    found = candidates()
    if len(found) != 1:
        print("无法安全地自动判断 TeslaMate 的 Nginx 站点配置。", file=sys.stderr)
        print("请重新运行并指定：--nginx-config /实际的站点配置文件", file=sys.stderr)
        if found:
            print("候选文件：", *map(str, found), sep="\n  ", file=sys.stderr)
        sys.exit(2)
if not target.is_file():
    print(f"Nginx 配置不存在：{target}", file=sys.stderr); sys.exit(2)

text = target.read_text()
marker = "# teslamate-cn-patches managed include"
if marker not in text:
    # Only edit a simple file containing exactly one proxying server block; otherwise stop.
    starts = [match.start() for match in re.finditer(r"(?m)^\s*server\s*\{", text)]
    if len(starts) != 1:
        print("该文件包含多个 server 块，已停止以避免写入错误站点。请拆分站点配置后重试。", file=sys.stderr); sys.exit(2)
    start = text.find("{", starts[0])
    depth = 0; end = None
    for i in range(start, len(text)):
        if text[i] == "{": depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0: end = i; break
    if end is None or "proxy_pass" not in text[start:end]:
        print("未找到可安全修改的反向代理 server 块。", file=sys.stderr); sys.exit(2)
    text = text[:end] + f"\n    include /etc/nginx/snippets/teslamate-cn-patches.conf; {marker}\n" + text[end:]

root = Path(args.root)
snippet = f'''# Generated by TeslaMate CN Patches. Safe to keep across upgrades.
proxy_set_header Accept-Encoding "";
sub_filter_once off;
sub_filter_types text/html;
sub_filter "</head>" "<script src=\\"/teslamate-cn-ui.js\\"></script><script defer src=\\"/grafana-nav-order.js\\"></script></head>";
location = /teslamate-cn-ui.js {{ alias {root}/assets/teslamate-cn-ui.js; default_type application/javascript; add_header Cache-Control "no-store"; }}
location = /grafana-nav-order.js {{ alias {root}/assets/grafana-nav-order.js; default_type application/javascript; add_header Cache-Control "no-store"; }}
'''
snippet_path = Path("/etc/nginx/snippets/teslamate-cn-patches.conf")
snippet_path.parent.mkdir(parents=True, exist_ok=True)
stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup = target.with_name(target.name + f".teslamate-cn-{stamp}.bak")
snippet_backup = snippet_path.with_name(snippet_path.name + f".{stamp}.bak") if snippet_path.exists() else None
shutil.copy2(target, backup)
if snippet_backup: shutil.copy2(snippet_path, snippet_backup)
target.write_text(text)
snippet_path.write_text(snippet)
result = subprocess.run(["nginx", "-t"], text=True, capture_output=True)
if result.returncode:
    shutil.copy2(backup, target)
    if snippet_backup: shutil.copy2(snippet_backup, snippet_path)
    else: snippet_path.unlink(missing_ok=True)
    print(result.stderr, file=sys.stderr)
    print(f"Nginx 测试失败，已自动恢复：{backup}", file=sys.stderr)
    sys.exit(1)
subprocess.run(["systemctl", "reload", "nginx"], check=True)
print(f"Nginx 已配置并重载。备份：{backup}")
